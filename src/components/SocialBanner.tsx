export function SocialBanner({ settings }: { settings: SiteSettings }) {
  if (!settings.bannerEnabled) return null;
  const links = socialLinks(settings);
  if (links.length === 0) return null;

  return (
    <div className="bg-neutral-900 text-accent">
      <div className="mx-auto flex max-w-6xl flex-col items-center justify-center gap-2 px-4 py-2 text-center sm:flex-row sm:gap-4">
        <p className="text-sm font-bold">{settings.bannerText}</p>
        <div className="flex items-center gap-2">
          {links.map((l) => (
            <a
              key={l.key}
              href={l.url}
              target="_blank"
              rel="noopener noreferrer"
              aria-label={l.label}
              title={l.label}
              className="rounded-full bg-accent p-1.5 text-neutral-900 transition hover:scale-110 hover:bg-white"
            >
              <svg viewBox="0 0 24 24" fill="currentColor" className="h-4 w-4" aria-hidden>
                {ICONS[l.key]}
              </svg>
            </a>
          ))}
        </div>
      </div>
    </div>
  );
}
